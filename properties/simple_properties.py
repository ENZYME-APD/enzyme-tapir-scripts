from archicad import ACConnection
import subprocess

def show_popup(title, message, is_error=False):
    icon = "stop" if is_error else "note"
    # Escape quotes
    message = message.replace('"', '\\"')
    title = title.replace('"', '\\"')
    script = f'display dialog "{message}" with title "{title}" buttons {{"OK"}} default button "OK" with icon {icon}'
    subprocess.run(["osascript", "-e", script])

def main():
    conn = ACConnection.connect()
    
    print("1. Creating Property Group 'Scripting'...")
    try:
        # Create Property Group
        conn.commands.ExecuteAddOnCommand(
            conn.types.AddOnCommandId("TapirCommand", "CreatePropertyGroups"),
            {"propertyGroups": [{"propertyGroup": {"name": "Scripting", "description": "Properties generated by scripts"}}]}
        )
        print("Property group created or already exists.")
    except Exception as e:
        print(f"Failed to create property group: {e}")

    # Fetch the group ID
    group_ids = conn.commands.GetAllPropertyGroupIds()
    groups = conn.commands.GetPropertyGroups(group_ids)
    scripting_group_id = None
    for g in groups:
        if g.propertyGroup.name == "Scripting":
            scripting_group_id = g.propertyGroup.propertyGroupId
            break
            
    if not scripting_group_id:
        print("Error: Could not find Scripting group.")
        return
        
    print("2. Fetching Classifications (Slab, Column, Beam, Wall)...")
    # Fetch classification system
    systems = conn.commands.GetAllClassificationSystems()
    # Assume the first system is the built-in Archicad Classification
    system_id = systems[0].classificationSystemId
    
    items = conn.commands.GetAllClassificationsInSystem(system_id)
    class_guids = []
    for item in items:
        try:
            class_guids.append(item.classificationItem.classificationItemId.guid)
        except AttributeError:
            pass
    
    print(f"Found {len(class_guids)} classification GUIDs.")

    print("3. Creating Property Definition 'ScriptID'...")
    # Create Property Definition
    payload = {
        "propertyDefinitions": [
            {
                "propertyDefinition": {
                    "name": "ScriptID_Final2",
                    "description": "Identifier for elements generated by scripts.",
                    "type": "string",
                    "isEditable": True,
                    "defaultValue": {
                        "basicDefaultValue": {
                            "type": "string",
                            "status": "normal",
                            "value": ""
                        }
                    },
                    "group": {
                        "propertyGroupId": {"guid": str(scripting_group_id.guid)}
                    },
                    "availability": [
                        {"classificationItemId": {"guid": str(c_guid)}} for c_guid in class_guids
                    ]
                }
            }
        ]
    }
    
    res = conn.commands.ExecuteAddOnCommand(
        conn.types.AddOnCommandId("TapirCommand", "CreatePropertyDefinitions"),
        payload
    )
    
    if res and "error" in res:
        msg = f"API Error creating property: {res['error']}\n\nNote: If the code is -2130312988, it usually means a property with this name already exists in the group!"
        print(msg)
        show_popup("Error", msg, is_error=True)
    elif res and "propertyIds" in res:
        has_error = False
        for item in res["propertyIds"]:
            if "error" in item:
                msg = f"API Error in propertyIds: {item['error']}\n\nNote: If the code is -2130312988, it usually means a property with this name already exists in the group!"
                print(msg)
                show_popup("Error", msg, is_error=True)
                has_error = True
        if not has_error:
            msg = "Property Definition 'ScriptID_Final2' created successfully and assigned to all classifications!"
            print(msg)
            show_popup("Success", msg)
    else:
        msg = "Property definition created."
        print(f"Response: {res}")
        print(msg)
        show_popup("Success", msg)

if __name__ == "__main__":
    main()
